export const categoryLabels: Record<RecipientCategory, { label: string; count: number }> = Object.keys(
  defaultCategoryMeta
).reduce((acc, cat) => {
  const c = cat as RecipientCategory;
  const count = allWishes.filter((w) => w.recipientCategory === c).length;
  acc[c] = {
    label: defaultCategoryMeta[c],
    count,
  };
  return acc;
}, {} as Record<RecipientCategory, { label: string; count: number }>);

export function getRandomWish(occasion?: string): WishItem {
  if (occasion) {
    const matched = allWishes.filter((w) => w.occasion === occasion);
    if (matched.length > 0) {
      return matched[Math.floor(Math.random() * matched.length)];
    }
  }
  return allWishes[Math.floor(Math.random() * allWishes.length)];
}
